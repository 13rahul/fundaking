/**
 * Exports case studies + topic guides to includes/related-content.php so the
 * PHP city / niche money pages can link into the Astro blog and case studies.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const blogDir = path.join(root, "src/content/blog");
const caseDir = path.join(root, "src/content/case-study");
const outFile = path.join(root, "..", "includes", "related-content.php");
const clusterMap = JSON.parse(
  fs.readFileSync(path.join(root, "scripts/cluster-map.json"), "utf8"),
);

const GUIDES_PER_PILLAR = 4;

function readEntries(dir) {
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".md") && !f.startsWith("-"))
    .map((f) => {
      const raw = fs.readFileSync(path.join(dir, f), "utf8");
      const m = raw.match(/^---\r?\n([\s\S]*?)\r?\n---/);
      const data = m ? yaml.load(m[1]) ?? {} : {};
      return { slug: f.replace(/\.md$/, ""), data };
    })
    .filter((e) => !e.data.draft);
}

function time(d) {
  const v = d.date_modified ?? d.date;
  return v ? new Date(v).getTime() : 0;
}

const posts = readEntries(blogDir);
const studies = readEntries(caseDir).sort((a, b) => time(b.data) - time(a.data));

const guides = {};
for (const [pillar, meta] of Object.entries(clusterMap.pillars)) {
  const pool = posts.filter((p) => clusterMap.posts[p.slug]?.pillar === pillar);
  const hub = pool.find((p) => p.slug === meta.hub);
  const rest = pool
    .filter((p) => p !== hub)
    .sort((a, b) => time(b.data) - time(a.data));
  guides[pillar] = [hub, ...rest]
    .filter(Boolean)
    .slice(0, GUIDES_PER_PILLAR)
    .map((p) => ({
      slug: p.slug,
      title: p.data.title,
      description: p.data.description ?? "",
      category: p.data.categories?.[0] ?? "Guide",
    }));
}

const proof = {};
for (const [pillar, meta] of Object.entries(clusterMap.pillars)) {
  const m = String(meta.proof ?? "").match(/^\/case-study\/([^/]+)/);
  if (m) proof[pillar] = m[1];
}

const payload = {
  studies: studies.map((s) => ({
    slug: s.slug,
    title: s.data.title,
    description: s.data.description ?? "",
    badge: s.data.badge ?? "Case study",
    stat: s.data.stats?.[0]
      ? `${s.data.stats[0].value} ${s.data.stats[0].label}`
      : "",
  })),
  guides,
  proof,
};

const php = `<?php
/**
 * Auto-generated by automark-astro-main/scripts/generate-php-related.mjs — do not edit.
 */
$fkRelated = json_decode(<<<'JSON'
${JSON.stringify(payload, null, 2)}
JSON, true);
`;

fs.writeFileSync(outFile, php, "utf8");
console.log(
  `[generate-php-related] ${payload.studies.length} case studies, ${Object.keys(guides).length} guide groups → includes/related-content.php`,
);
