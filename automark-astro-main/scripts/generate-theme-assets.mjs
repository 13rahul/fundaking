import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const distIndex = join(root, "dist", "index.html");
const outPhp = join(root, "..", "includes", "theme-assets.php");

if (!existsSync(distIndex)) {
  console.warn("skip theme-assets.php (dist/index.html missing)");
  process.exit(0);
}

const html = readFileSync(distIndex, "utf8");
const styles = [
  ...html.matchAll(/href="(\/_astro\/[^"]+\.css)"/g),
].map((m) => m[1]);
const normalize = (p) => p.replace(/^\/fundaking(?=\/)/, "");
const uniqueStyles = [...new Set(styles.map(normalize))];

const scripts = [
  ...html.matchAll(/src="(\/scripts\/[^"]+\.js)"/g),
].map((m) => m[1]);
const uniqueScripts = [...new Set(scripts.map(normalize))];

const php = `<?php
/**
 * Auto-generated by automark-astro-main build:main — do not edit manually.
 * Run: npm run build:main
 */
$themeStylesheets = ${JSON.stringify(uniqueStyles, null, 4)
  .replace(/"/g, "'")
  .replace(/'/g, "'")};
$themeScripts = ${JSON.stringify(uniqueScripts, null, 4)
  .replace(/"/g, "'")
  .replace(/'/g, "'")};
`;

// Fix JSON to PHP array syntax
const phpFixed = `<?php
/**
 * Auto-generated by automark-astro-main build:main — do not edit manually.
 */
$themeStylesheets = [
${uniqueStyles.map((s) => `    '${s}',`).join("\n")}
];
$themeScripts = [
${uniqueScripts.map((s) => `    '${s}',`).join("\n")}
];
`;

writeFileSync(outPhp, phpFixed);
console.log(`Wrote ${outPhp}`);
